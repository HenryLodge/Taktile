#!/usr/bin/env node
// Generate the checksum word table (PGP "even" words) for the device and the app.
//
//   node tools/gen-words.mjs           write core/include/tk_words.h, core/src/tk_words.c, app/src/words.ts
//   node tools/gen-words.mjs --check   write nothing; exit 1 if any of them is stale
//
// Source of truth: tools/data/pgp-even-words.txt (line N = byte N). No dependencies.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const WORDS_FILE = 'tools/data/pgp-even-words.txt';

// Parse and validate the list: exactly 256 words, letters only, unique ignoring case.
export function parseWords(text) {
    const words = text
        .split(/\r?\n/)
        .map((l) => l.trim())
        .filter((l) => l !== '' && !l.startsWith('#'));
    if (words.length !== 256) {
        throw new Error(`${WORDS_FILE}: expected 256 words, got ${words.length}`);
    }
    const seen = new Set();
    for (const w of words) {
        if (!/^[A-Za-z]+$/.test(w)) {
            throw new Error(`${WORDS_FILE}: not letters only: ${JSON.stringify(w)}`);
        }
        if (seen.has(w.toLowerCase())) {
            throw new Error(`${WORDS_FILE}: duplicate word ${w}`);
        }
        seen.add(w.toLowerCase());
    }
    return words;
}

export function loadWords() {
    return parseWords(readFileSync(join(ROOT, WORDS_FILE), 'utf8'));
}

const C_BANNER = `// GENERATED by tools/gen-words.mjs from ${WORDS_FILE}. Do not edit; rerun the script.\n`;

function renderHeader() {
    return [
        C_BANNER,
        '// Checksum phrase words: the PGP word list "even" words (Juola & Zimmermann, 1995). See docs/AUDIO.md.',
        '',
        '#ifndef TK_WORDS_H',
        '#define TK_WORDS_H',
        '',
        '#include <stdint.h>',
        '',
        '#define TK_WORD_COUNT 256u',
        '',
        '// The word for a phrase index (a hash byte). The device plays words as clips by index; the text',
        '// is for sim/, tests and clip generation.',
        'const char *tk_word(uint8_t index);',
        '',
        '#endif',
        '',
    ].join('\n');
}

function renderSource(words) {
    const out = [C_BANNER, '#include "tk_words.h"', '', 'static const char *const WORDS[TK_WORD_COUNT] = {'];
    for (let i = 0; i < words.length; i += 6) {
        out.push('    ' + words.slice(i, i + 6).map((w) => `"${w}",`).join(' '));
    }
    out.push('};', '', 'const char *tk_word(uint8_t index) {', '    return WORDS[index];', '}', '');
    return out.join('\n');
}

function renderTs(words) {
    const out = [
        `// GENERATED by tools/gen-words.mjs from ${WORDS_FILE}. Do not edit; rerun the script.`,
        '// Checksum phrase words: the PGP word list "even" words (Juola & Zimmermann, 1995). See docs/AUDIO.md.',
        '',
        'export const PGP_EVEN_WORDS: readonly string[] = Object.freeze([',
    ];
    for (let i = 0; i < words.length; i += 6) {
        out.push('    ' + words.slice(i, i + 6).map((w) => `'${w}',`).join(' '));
    }
    out.push(']);', '');
    return out.join('\n');
}

// Returns [[relativePath, contents], ...]. Deterministic, LF only.
export function generate(words = loadWords()) {
    return [
        ['core/include/tk_words.h', renderHeader()],
        ['core/src/tk_words.c', renderSource(words)],
        ['app/src/words.ts', renderTs(words)],
    ];
}

function main(argv) {
    const files = generate();
    if (!argv.includes('--check')) {
        for (const [rel, text] of files) {
            writeFileSync(join(ROOT, rel), text);
            console.log(`wrote ${rel}`);
        }
        return 0;
    }
    let ok = true;
    for (const [rel, text] of files) {
        let current = null;
        try {
            current = readFileSync(join(ROOT, rel), 'utf8').replace(/\r\n/g, '\n');
        } catch {
            // missing: reported below
        }
        if (current !== text) {
            console.error(`stale: ${rel} (run node tools/gen-words.mjs)`);
            ok = false;
        }
    }
    if (ok) {
        console.log('words: up to date');
    }
    return ok ? 0 : 1;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
    process.exitCode = main(process.argv.slice(2));
}
